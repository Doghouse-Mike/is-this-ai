const BENIGN_ACTIONS = new Set(["created", "opened", "published"]);

// Unsigned markers: [regex, finding, severity]. Matched only against readable
// text metadata, never compressed data: short names like "xai" occur by chance
// in binary. Editors count only when named as the producing software, because
// Apple and others write Adobe's XMP "photoshop:" namespace and "Photoshop 3.0"
// IPTC blocks without Photoshop being involved.
const EDITOR = String.raw`(?:CreatorTool|Software|softwareAgent)\W{1,4}[^<>"\x00\n]{0,60}?`;
const MARKERS = [
  [/trainedAlgorithmicMedia/, "IPTC source type 'trainedAlgorithmicMedia' (AI-generated) embedded in metadata", "ai"],
  [/compositeWithTrainedAlgorithmicMedia/, "IPTC source type 'composite with AI-generated content' embedded in metadata", "ai"],
  [/Made with Google AI|Edited with Google AI|Google AI/, "Google AI (Gemini/Imagen) marker in metadata", "ai"],
  [/midjourney/i, "Midjourney marker in metadata", "ai"],
  [/\bdall[-· ]?e\b/i, "DALL-E marker in metadata", "ai"],
  [/stable ?diffusion|ComfyUI|\bsdxl\b/i, "Stable Diffusion / ComfyUI marker in metadata", "ai"],
  [/Apple Photos Generative|Clean Up/, "Apple Photos generative edit (Clean Up) recorded in metadata", "ai"],
  [/adobe firefly|generative fill/i, "Adobe Firefly / Generative Fill marker in metadata", "ai"],
  [/\bgrok\b|\bxai\b|\bflux\.?1\b|ideogram|leonardo\.ai/i, "AI image service marker in metadata", "ai"],
  [/tEXtparameters|iTXtparameters/, "PNG 'parameters' text chunk (Stable Diffusion generation settings)", "ai"],
  [/tEXtprompt|tEXtworkflow/, "PNG 'prompt'/'workflow' text chunk (ComfyUI generation settings)", "ai"],
  [new RegExp(EDITOR + "photoshop", "i"), "Edited in Adobe Photoshop (named as the producing software)", "edit"],
  [new RegExp(EDITOR + String.raw`\bGIMP\b`, "i"), "Edited in GIMP (named as the producing software)", "edit"],
  [new RegExp(EDITOR + "(?:snapseed|lightroom|picsart|facetune|canva|pixelmator|affinity)", "i"),
    "Processed by a photo-editing app (named as the producing software)", "edit"],
];

