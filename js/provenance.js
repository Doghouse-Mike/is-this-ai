// Image provenance analysis, run entirely in the browser.
//
// Evidence sources, strongest first:
//   1. C2PA Content Credentials, cryptographically verified (c2pa-web, the
//      official CAI WebAssembly build of c2pa-rs) against the C2PA trust list.
//   2. Unsigned markers in readable metadata (XMP, PNG text, EXIF strings).
//   3. Camera metadata (EXIF): presence supports a real capture, absence
//      proves nothing because chat apps strip it.
//
// Ported from the local `image-provenance` tool, including the false-positive
// fixes found by scanning 1000 real images (see README).

